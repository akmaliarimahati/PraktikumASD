package Praktikum14;

public class Customer04 {
    public int id;
    public String name;

    public Customer04() {

    }

    public Customer04(int id, String name) {
        this.id = id;
        this.name = name;
    }

    public String toString() {
        return " ID: " + this.id + " Nama: " + this.name;
    }
}
